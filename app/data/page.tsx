"use client";
import { useEffect, useState } from "react";
import { Alert, btnPrimary } from "@/components/ui/primitives";
export default function DataPage() {
  const [me, setMe] = useState<{ participantId: string | null; questionsAsked: number; hasData: boolean } | null>(null);
  const [counts, setCounts] = useState<{ real: number; simulated: number }>({ real: 0, simulated: 0 });
  const [confirming, setConfirming] = useState(false);
  const [erased, setErased] = useState(false);
  useEffect(() => {
    fetch("/api/me").then((r) => r.json()).then(setMe).catch(() => {});
    Promise.all([
      fetch("/api/lab/summary?traffic=real").then((r) => r.json()),
      fetch("/api/lab/summary?traffic=simulated").then((r) => r.json()),
    ]).then(([a, b]) => setCounts({ real: a.participants || 0, simulated: b.participants || 0 })).catch(() => {});
  }, []);
  async function erase() {
    await fetch("/api/me", { method: "DELETE" }).catch(() => {});
    setConfirming(false); setErased(true); setMe({ participantId: null, questionsAsked: 0, hasData: false });
  }
  const H2 = "mt-10 font-display text-[28px] font-semibold";
  const P = "mt-3 leading-7 text-ink-2";
  return (
    <div className="mx-auto w-full max-w-[680px] px-4 py-10 md:px-6">
      <h1 className="font-display text-[30px] font-semibold leading-9 md:text-[38px] md:leading-[44px]">Data and privacy</h1>
      <h2 className={H2}>What we collect</h2>
      <p className={P}>The question text and the answer you receive; whether you marked it helpful; an anonymous random ID stored in one cookie; the timing and cost of each answer.</p>
      <h2 className={H2}>What we do not collect</h2>
      <p className={P}>Your name, email, account, network address (only a salted hash held in memory for rate limiting), or any advertising identifier. There are no analytics scripts and no third-party requests from your browser; fonts are self-hosted.</p>
      <h2 className={H2}>The cookie</h2>
      <p className={P}><span className="font-mono text-[15px]">vd_pid</span>, first party, HttpOnly, one year. It exists only to give you a stable anonymous ID, which the experiment needs in order to show you the same version every time. It is strictly necessary for the experiment to function.</p>
      <h2 className={H2}>Why</h2>
      <p className={P}>To run the experiment described on the <a href="/method" className="text-accent underline">Method page</a>.</p>
      <h2 className={H2}>Retention</h2>
      <p className={P}>Questions, answers and feedback are kept until the end of the hackathon judging period plus a short grace period (until 31 December 2026), then deleted.</p>
      <div className="mt-6"><Alert kind="warning">Please do not enter personal data into questions.</Alert></div>
      <h2 className={H2}>Erase my data</h2>
      {erased ? <div className="mt-3"><Alert kind="success">Your data was erased and the cookie removed.</Alert></div> : (
        <>
          <p className={P}>Your anonymous ID prefix: <span className="font-mono">{me?.participantId || "none yet"}</span>. Questions asked from this browser: <span className="font-mono">{me?.questionsAsked ?? 0}</span>.</p>
          <button disabled={!me?.hasData} onClick={() => setConfirming(true)} className="mt-4 inline-flex min-h-[44px] items-center rounded bg-danger px-5 py-2.5 text-[15px] font-medium text-white transition-opacity hover:opacity-90 disabled:bg-surface-2 disabled:text-ink-3">Erase my data</button>
        </>
      )}
      {confirming && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-ink/40 p-4" role="dialog" aria-modal="true" aria-label="Confirm erase">
          <div className="w-full max-w-[440px] rounded-[10px] border border-border-strong bg-surface p-5">
            <h3 className="font-display text-xl font-semibold">Erase my data</h3>
            <p className="mt-2 text-sm text-ink-2">Erase your questions and feedback and remove the cookie? This cannot be undone.</p>
            <div className="mt-4 flex gap-2">
              <button onClick={erase} className="inline-flex min-h-[44px] items-center rounded bg-danger px-4 text-sm font-medium text-white hover:opacity-90">Erase</button>
              <button onClick={() => setConfirming(false)} className="inline-flex min-h-[44px] items-center rounded border border-border-strong bg-surface px-4 text-sm font-medium hover:bg-surface-2">Cancel</button>
            </div>
          </div>
        </div>
      )}
      <h2 id="traffic" className={H2}>Traffic disclosure</h2>
      <p className={P}>Some visitors in this experiment are simulated. Simulated visitors are generated by the script <span className="font-mono text-[15px]">scripts/simulate.ts</span> in the repository, use IDs starting with <span className="font-mono text-[15px]">sim-</span>, and are always shown separately. Headline conclusions use real visitors only.</p>
      <p className={P}>Right now: <span className="font-mono">{counts.real}</span> real participants, <span className="font-mono">{counts.simulated}</span> simulated participants.</p>
      <h2 className={H2}>Documentation source and licence</h2>
      <p className={P}>Answers come from the public Flagsmith documentation (github.com/Flagsmith/flagsmith, the docs folder), BSD-3-Clause licence, Copyright Bullet Train Ltd and contributors. This project is not affiliated with or endorsed by Flagsmith.</p>
    </div>
  );
}
